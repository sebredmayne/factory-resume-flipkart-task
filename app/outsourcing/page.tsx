import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { Badge } from "@/components/ui/badge";
import { providers } from "@/lib/data";
import { formatCurrency, formatNumber } from "@/lib/format";

export default function OutsourcingPage() {
  const totalCapacity = providers.reduce(
    (sum, p) => sum + p.availableCapacity,
    0
  );

  return (
    <div className="flex flex-col gap-8">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight">
          Outsourcing partners
        </h1>
        <p className="text-muted-foreground">
          {providers.length} eligible external providers ·{" "}
          {formatNumber(totalCapacity)} units/day of confirmed external
          capacity.
        </p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>External provider capacity</CardTitle>
          <CardDescription>
            Recommendations on what to outsource, and why, are generated by
            the recovery engine once it is wired in.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Provider</TableHead>
                <TableHead>Services</TableHead>
                <TableHead>Capacity / day</TableHead>
                <TableHead>Cost / unit</TableHead>
                <TableHead>Activation time</TableHead>
                <TableHead>Locations</TableHead>
                <TableHead>Quality requirements</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {providers.map((provider) => (
                <TableRow key={provider.id}>
                  <TableCell className="font-medium">
                    {provider.name}
                  </TableCell>
                  <TableCell>
                    <div className="flex flex-wrap gap-1">
                      {provider.services.map((service) => (
                        <Badge key={service} variant="outline">
                          {service}
                        </Badge>
                      ))}
                    </div>
                  </TableCell>
                  <TableCell>{formatNumber(provider.availableCapacity)}</TableCell>
                  <TableCell>{formatCurrency(provider.costPerUnit)}</TableCell>
                  <TableCell>{provider.activationHours}h</TableCell>
                  <TableCell className="text-muted-foreground">
                    {provider.supportedLocations.join(", ")}
                  </TableCell>
                  <TableCell className="text-muted-foreground">
                    {provider.qualityRequirements ?? "None specified"}
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>
    </div>
  );
}
